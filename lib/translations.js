/**
 * @param {Locale} locale
 * @param {'event' | 'admin' | 'common'} ns
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 */
export function t(locale, ns, key, vars) {
  const bucket = translations[locale]?.[ns] ?? translations[DEFAULT_LOCALE][ns]
  let text = /** @type {Record<string, string>} */ (bucket)?.[key] ?? key
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v))
    })
  }
  return text
}

